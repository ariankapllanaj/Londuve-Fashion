const listeners = new Set();
let current = 'en';

export function detectLang() {
  const url = new URLSearchParams(location.search).get('lang');
  if (url && LANGS.includes(url)) return url;
  try {
    const saved = localStorage.getItem('londuve-lang');
    if (saved && LANGS.includes(saved)) return saved;
  } catch (e) { /* storage unavailable */ }
  const nav = (navigator.languages || [navigator.language || 'en']).map((l) => l.slice(0, 2).toLowerCase());
  return nav.find((l) => LANGS.includes(l)) || 'en';
}

let vars = {};
/** Values substituted into {placeholders} in the strings (e.g. {price}, {volume} from CONFIG.product). */
export const setVars = (v) => { vars = { ...vars, ...v }; };
const fill = (s) => (typeof s === 'string' ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s);
export const t = (key) => fill((DICT[current] && DICT[current][key]) ?? DICT.en[key] ?? key);
export const getLang = () => current;
export const onLangChange = (fn) => listeners.add(fn);

export function setLang(lang, { silent = false } = {}) {
  if (!LANGS.includes(lang)) lang = 'en';
  current = lang;
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  const md = document.querySelector('meta[name="description"]');
  if (md) md.setAttribute('content', t('meta.desc'));

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-lang]').forEach((b) => {
    b.classList.toggle('is-active', b.dataset.lang === lang);
    b.setAttribute('aria-pressed', b.dataset.lang === lang ? 'true' : 'false');
  });
  try { localStorage.setItem('londuve-lang', lang); } catch (e) { /* ignore */ }
  if (!silent) listeners.forEach((fn) => fn(lang));
}
